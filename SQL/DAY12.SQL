# SQL Day 12 – DELETE

## DELETE
Used to remove rows from a table.

Syntax:
DELETE FROM table_name
WHERE condition;

## Important Points
• DELETE removes complete rows.
• WHERE specifies which rows to delete.
• Without WHERE, every row is deleted.
• Always verify the rows first using a SELECT query.
• DELETE removes data, not the table structure.

## CRUD Summary
CREATE → INSERT
READ   → SELECT
UPDATE → UPDATE
DELETE → DELETE